/*
 * Replace the whole of texture `id` with rows of `stride` bytes, as `upload` does (a command
 * buffer of its own, submitted now, so before the frame that draws it) — but through one
 * transfer buffer kept for the purpose and cycled, not a new one per call: a movie frame is
 * 11 MB, sixty times a second.
 */
bool host_texture_upload(int id, const void *px, size_t stride) {
  static SDL_GPUTransferBuffer *tb;
  static Uint32 tb_size;
  SDL_GPUTexture *t = tex_by_id(id);
  if (!t || stride % 4) return false;
  Uint32 size = (Uint32)(stride * (size_t)tex_h[id]);
  if (size > tb_size) {
    if (tb) SDL_ReleaseGPUTransferBuffer(dev, tb);
    SDL_GPUTransferBufferCreateInfo ti = {.usage = SDL_GPU_TRANSFERBUFFERUSAGE_UPLOAD, .size = size};
    tb = SDL_CreateGPUTransferBuffer(dev, &ti);
    tb_size = tb ? size : 0;
    if (!tb) return false;
  }
  void *dst = SDL_MapGPUTransferBuffer(dev, tb, true); /* cycled: never waits on the last upload */
  if (!dst) return false;
  memcpy(dst, px, size);
  SDL_UnmapGPUTransferBuffer(dev, tb);
  SDL_GPUCommandBuffer *c = SDL_AcquireGPUCommandBuffer(dev);
  SDL_GPUCopyPass *cp = SDL_BeginGPUCopyPass(c);
  SDL_GPUTextureTransferInfo src = {.transfer_buffer = tb, .pixels_per_row = (Uint32)(stride / 4), .rows_per_layer = (Uint32)tex_h[id]};
  SDL_GPUTextureRegion region = {.texture = t, .w = (Uint32)tex_w[id], .h = (Uint32)tex_h[id], .d = 1};
  SDL_UploadToGPUTexture(cp, &src, &region, true);
  SDL_EndGPUCopyPass(cp);
  SDL_SubmitGPUCommandBuffer(c);
  return true;
}

void host_texture_release(int id) {
  flush_surf();
  SDL_GPUTexture *t = tex_by_id(id);
  if (t) { SDL_ReleaseGPUTexture(dev, t); textures[id] = NULL; }
}

