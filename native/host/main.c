typedef struct {
  int32_t scale, bgW, wobble, ripN;
  float amp, per, phase, pad;
  float rip[3][4];
  float ripPh[4];
} BgU;

static JSValue n_background(JSContext *ctx, JSValueConst self, int argc, JSValueConst *argv) {
  SDL_GPUTexture *bg = tex_by_id(ARGI(0)), *wall = tex_by_id(ARGI(1));
  if (!bg || !wall) return JS_ThrowTypeError(ctx, "background: unknown texture");
  BgU u = {0};
  u.scale = ARGI(2);
  u.bgW = ARGI(3);
  u.wobble = JS_ToBool(ctx, argv[4]) ? 1 : 0;
  u.amp = (float)ARGF(5);
  u.per = (float)ARGF(6);
  u.phase = (float)ARGF(7);
  u.ripN = ARGI(8);
  for (int i = 0; i < 12; i++) {
    JSValue v = JS_GetPropertyUint32(ctx, argv[9], (uint32_t)i);
    double d = 0;
    JS_ToFloat64(ctx, &d, v);
    JS_FreeValue(ctx, v);
    u.rip[i / 4][i % 4] = (float)d;
  }
  for (int i = 0; i < 3; i++) {
    JSValue v = JS_GetPropertyUint32(ctx, argv[10], (uint32_t)i);
    double d = 0;
    JS_ToFloat64(ctx, &d, v);
    JS_FreeValue(ctx, v);
    u.ripPh[i] = (float)d;
  }
  use(p_bg);
  SDL_PushGPUFragmentUniformData(cmd, 0, &u, sizeof u);
  SDL_GPUTextureSamplerBinding b[2] = {{bg, s_nearest}, {wall, s_nearest}};
  SDL_BindGPUFragmentSamplers(pass, 0, b, 2);
  SDL_DrawGPUPrimitives(pass, 3, 1, 0, 0);
  return JS_UNDEFINED;
}

