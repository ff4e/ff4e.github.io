static void die(const char *what) {
  SDL_Log("fatal: %s: %s", what, SDL_GetError());
  exit(1);
}

static SDL_GPUShader *shader(const char *entry, SDL_GPUShaderStage stage, Uint32 samplers, Uint32 uniforms) {
  SDL_GPUShaderCreateInfo ci = {0};
  ci.code = (const Uint8 *)SHADERS_MSL;
  ci.code_size = sizeof(SHADERS_MSL) - 1;
  ci.entrypoint = entry;
  ci.format = SDL_GPU_SHADERFORMAT_MSL;
  ci.stage = stage;
  ci.num_samplers = samplers;
  ci.num_uniform_buffers = uniforms;
  SDL_GPUShader *s = SDL_CreateGPUShader(dev, &ci);
  if (!s) die(entry);
  return s;
}

static SDL_GPUGraphicsPipeline *pipeline(const char *vs, Uint32 vs_uniforms, const char *fs, Uint32 fs_samplers,
                                         SDL_GPUTextureFormat fmt, bool blend, bool strip) {
  SDL_GPUShader *v = shader(vs, SDL_GPU_SHADERSTAGE_VERTEX, 0, vs_uniforms);
  SDL_GPUShader *f = shader(fs, SDL_GPU_SHADERSTAGE_FRAGMENT, fs_samplers, 1);
  SDL_GPUColorTargetDescription ct = {0};
  ct.format = fmt;
  if (blend) {
    /* GlAiScreen: blendFuncSeparate(SRC_ALPHA, ONE_MINUS_SRC_ALPHA, ONE, ONE_MINUS_SRC_ALPHA) */
    ct.blend_state.enable_blend = true;
    ct.blend_state.src_color_blendfactor = SDL_GPU_BLENDFACTOR_SRC_ALPHA;
    ct.blend_state.dst_color_blendfactor = SDL_GPU_BLENDFACTOR_ONE_MINUS_SRC_ALPHA;
    ct.blend_state.color_blend_op = SDL_GPU_BLENDOP_ADD;
    ct.blend_state.src_alpha_blendfactor = SDL_GPU_BLENDFACTOR_ONE;
    ct.blend_state.dst_alpha_blendfactor = SDL_GPU_BLENDFACTOR_ONE_MINUS_SRC_ALPHA;
    ct.blend_state.alpha_blend_op = SDL_GPU_BLENDOP_ADD;
  }
  SDL_GPUGraphicsPipelineCreateInfo pi = {0};
  pi.vertex_shader = v;
  pi.fragment_shader = f;
  pi.primitive_type = strip ? SDL_GPU_PRIMITIVETYPE_TRIANGLESTRIP : SDL_GPU_PRIMITIVETYPE_TRIANGLELIST;
  pi.rasterizer_state.cull_mode = SDL_GPU_CULLMODE_NONE;
  pi.target_info.color_target_descriptions = &ct;
  pi.target_info.num_color_targets = 1;
  SDL_GPUGraphicsPipeline *p = SDL_CreateGPUGraphicsPipeline(dev, &pi);
  if (!p) die(fs);
  SDL_ReleaseGPUShader(dev, v);
  SDL_ReleaseGPUShader(dev, f);
  return p;
}

static SDL_GPUTexture *make_texture(SDL_GPUTextureFormat fmt, int w, int h, SDL_GPUTextureUsageFlags usage) {
  SDL_GPUTextureCreateInfo ci = {0};
  ci.type = SDL_GPU_TEXTURETYPE_2D;
  ci.format = fmt;
  ci.usage = usage;
  ci.width = (Uint32)w;
  ci.height = (Uint32)h;
  ci.layer_count_or_depth = 1;
  ci.num_levels = 1;
  SDL_GPUTexture *t = SDL_CreateGPUTexture(dev, &ci);
  if (!t) die("SDL_CreateGPUTexture");
  return t;
}

/* Record an upload of `px` into the (x, y, w, h) rect of `t` on command buffer `c`. */
static void copy_rect(SDL_GPUCommandBuffer *c, SDL_GPUTexture *t, const void *px, int x, int y, int w, int h, int bpp) {
  Uint32 size = (Uint32)(w * h * bpp);
  SDL_GPUTransferBufferCreateInfo ti = {.usage = SDL_GPU_TRANSFERBUFFERUSAGE_UPLOAD, .size = size};
  SDL_GPUTransferBuffer *tb = SDL_CreateGPUTransferBuffer(dev, &ti);
  memcpy(SDL_MapGPUTransferBuffer(dev, tb, false), px, size);
  SDL_UnmapGPUTransferBuffer(dev, tb);
  SDL_GPUCopyPass *cp = SDL_BeginGPUCopyPass(c);
  SDL_GPUTextureTransferInfo src = {.transfer_buffer = tb, .pixels_per_row = (Uint32)w, .rows_per_layer = (Uint32)h};
  SDL_GPUTextureRegion dst = {.texture = t, .x = (Uint32)x, .y = (Uint32)y, .w = (Uint32)w, .h = (Uint32)h, .d = 1};
  SDL_UploadToGPUTexture(cp, &src, &dst, false);
  SDL_EndGPUCopyPass(cp);
  SDL_ReleaseGPUTransferBuffer(dev, tb); /* deferred by SDL until `c` has run */
}

static void copy_to(SDL_GPUCommandBuffer *c, SDL_GPUTexture *t, const void *px, int w, int h, int bpp) {
  copy_rect(c, t, px, 0, 0, w, h, bpp);
}

/*
 * Upload on a command buffer of its own, submitted now. Called from JS before the draw
 * that samples `t` is recorded, so it is also submitted — and run — before that draw's
 * frame command buffer.
 */
static void upload_region(SDL_GPUTexture *t, const void *px, int x, int y, int w, int h, int bpp) {
  SDL_GPUCommandBuffer *c = SDL_AcquireGPUCommandBuffer(dev);
  copy_rect(c, t, px, x, y, w, h, bpp);
  SDL_SubmitGPUCommandBuffer(c);
}

static void upload(SDL_GPUTexture *t, const void *px, int w, int h, int bpp) {
  upload_region(t, px, 0, 0, w, h, bpp);
}

static int add_texture(SDL_GPUTexture *t, int w, int h) {
  if (tex_count + 1 >= tex_cap) {
    tex_cap = tex_cap ? tex_cap * 2 : 256;
    textures = SDL_realloc(textures, sizeof *textures * (size_t)tex_cap);
    tex_w = SDL_realloc(tex_w, sizeof *tex_w * (size_t)tex_cap);
    tex_h = SDL_realloc(tex_h, sizeof *tex_h * (size_t)tex_cap);
  }
  textures[++tex_count] = t;
  tex_w[tex_count] = w;
  tex_h[tex_count] = h;
  return tex_count;
}

static SDL_GPUTexture *tex_by_id(int id) {
  return (id > 0 && id <= tex_count) ? textures[id] : NULL;
}

/* Bind a pipeline once per run of same-pipeline draws inside the composite pass. */
static void open_composite(SDL_GPULoadOp load);

static void use(SDL_GPUGraphicsPipeline *p) {
  if (!pass) open_composite(SDL_GPU_LOADOP_LOAD); /* a Surface2D flush closed it mid-frame */
  if (bound != p) {
    SDL_BindGPUGraphicsPipeline(pass, p);
    bound = p;
  }
}

typedef struct { float rect[4]; float size[2]; float pad[2]; } RectU;

static void push_rect(float x0, float y0, float x1, float y1) {
  RectU r = {{x0, y0, x1, y1}, {(float)comp_w, (float)comp_h}, {0, 0}};
  SDL_PushGPUVertexUniformData(cmd, 0, &r, sizeof r);
}

static void end_composite(void) {
  if (pass) {
    SDL_EndGPURenderPass(pass);
    pass = NULL;
    bound = NULL;
  }
}

