/* ── Surface2D on the GPU (src/render/surface2d.ts; native/js/nativeSurface.ts) ──────
 *
 * A surface is an RGBA8 render target holding PREMULTIPLIED colour, as a 2D canvas's
 * backing store does; every image a surface draws is premultiplied too (decodeImage,
 * surfPut), with the canvas's rounding — round(c·a/255) — so what reaches the blend is
 * the same 8-bit value a canvas would hand it.
 *
 * The batcher: `surfQuad` only STAGES a quad (six vertices in a CPU array), merging it into
 * the previous draw when target, texture, filter and blend all match. Everything that has
 * to happen in order with those quads — a clear, a pixel upload, a readback, presenting,
 * the room's own passes, releasing a texture — flushes first: one vertex upload for all of
 * them, then one render pass per run of draws into the same target. All of it is recorded
 * on the frame's command buffer, so an upload lands between the draws before and after it
 * exactly as a canvas's putImageData does, even into a surface already drawn this frame.
 */
typedef struct { float x, y, u, v, r, g, b, a; } SurfVert;
typedef struct { int target, tex, linear, blend; Uint32 first, count; } SurfDraw;
static SurfVert *sv;
static Uint32 sv_n, sv_cap;
static SurfDraw *sd;
static int sd_n, sd_cap;
static SDL_GPUGraphicsPipeline *p_surf[2]; /* [0] source-over, [1] destination-in */
static SDL_GPUTexture *white_tex;          /* what a fillRect samples */

static void flush_surf(void) {
  if (!sd_n) return;
  end_composite();
  if (!cmd) cmd = SDL_AcquireGPUCommandBuffer(dev);
  Uint32 size = sv_n * (Uint32)sizeof(SurfVert);
  SDL_GPUBufferCreateInfo bi = {.usage = SDL_GPU_BUFFERUSAGE_VERTEX, .size = size};
  SDL_GPUBuffer *vb = SDL_CreateGPUBuffer(dev, &bi);
  SDL_GPUTransferBufferCreateInfo ti = {.usage = SDL_GPU_TRANSFERBUFFERUSAGE_UPLOAD, .size = size};
  SDL_GPUTransferBuffer *tb = SDL_CreateGPUTransferBuffer(dev, &ti);
  if (!vb || !tb) die("surface vertex buffer");
  memcpy(SDL_MapGPUTransferBuffer(dev, tb, false), sv, size);
  SDL_UnmapGPUTransferBuffer(dev, tb);
  SDL_GPUCopyPass *cp = SDL_BeginGPUCopyPass(cmd);
  SDL_GPUTransferBufferLocation from = {.transfer_buffer = tb};
  SDL_GPUBufferRegion to = {.buffer = vb, .size = size};
  SDL_UploadToGPUBuffer(cp, &from, &to, false);
  SDL_EndGPUCopyPass(cp);
  for (int i = 0; i < sd_n;) {
    int t = sd[i].target;
    SDL_GPUColorTargetInfo ct = {0};
    ct.texture = tex_by_id(t);
    ct.load_op = SDL_GPU_LOADOP_LOAD;
    ct.store_op = SDL_GPU_STOREOP_STORE;
    SDL_GPURenderPass *rp = SDL_BeginGPURenderPass(cmd, &ct, 1, NULL);
    SDL_GPUBufferBinding vbind = {vb, 0};
    SDL_BindGPUVertexBuffers(rp, 0, &vbind, 1);
    float u[4] = {(float)tex_w[t], (float)tex_h[t], 0, 0};
    SDL_PushGPUVertexUniformData(cmd, 0, u, sizeof u);
    for (; i < sd_n && sd[i].target == t; i++) {
      SDL_BindGPUGraphicsPipeline(rp, p_surf[sd[i].blend]);
      SDL_GPUTexture *src = sd[i].tex ? tex_by_id(sd[i].tex) : white_tex;
      SDL_GPUTextureSamplerBinding b = {src, sd[i].linear ? s_linear : s_nearest};
      SDL_BindGPUFragmentSamplers(rp, 0, &b, 1);
      SDL_DrawGPUPrimitives(rp, sd[i].count, 1, sd[i].first, 0);
    }
    SDL_EndGPURenderPass(rp);
  }
  SDL_ReleaseGPUTransferBuffer(dev, tb); /* both deferred by SDL until `cmd` has run */
  SDL_ReleaseGPUBuffer(dev, vb);
  sv_n = 0;
  sd_n = 0;
}

/* Clear a render target to transparent black, in order with everything staged before. */
static void clear_target(SDL_GPUTexture *t) {
  flush_surf();
  end_composite();
  if (!cmd) cmd = SDL_AcquireGPUCommandBuffer(dev);
  SDL_GPUColorTargetInfo ct = {0};
  ct.texture = t;
  ct.load_op = SDL_GPU_LOADOP_CLEAR;
  ct.store_op = SDL_GPU_STOREOP_STORE;
  SDL_EndGPURenderPass(SDL_BeginGPURenderPass(cmd, &ct, 1, NULL));
}

/* The canvas's premultiply: round(c·a/255), in place. */
static void premultiply(uint8_t *px, size_t n) {
  for (size_t i = 0; i < n; i += 4) {
    unsigned a = px[i + 3];
    if (a == 255) continue;
    for (int c = 0; c < 3; c++) px[i + c] = (uint8_t)((px[i + c] * a + 127) / 255);
  }
}

static JSValue n_surfCreate(JSContext *ctx, JSValueConst self, int argc, JSValueConst *argv) {
  int w = ARGI(0), h = ARGI(1);
  if (w <= 0 || h <= 0) return JS_ThrowTypeError(ctx, "surfCreate: bad size %dx%d", w, h);
  SDL_GPUTexture *t = make_texture(SDL_GPU_TEXTUREFORMAT_R8G8B8A8_UNORM, w, h,
                                   SDL_GPU_TEXTUREUSAGE_COLOR_TARGET | SDL_GPU_TEXTUREUSAGE_SAMPLER);
  clear_target(t); /* a new canvas is transparent; new GPU memory is whatever it was */
  return JS_NewInt32(ctx, add_texture(t, w, h));
}

/*
 * Stage one quad: dest rect (x0,y0)-(x1,y1) in the target's pixels, source rect in the
 * texture's normalised coordinates, and a premultiplied colour the texel is multiplied by
 * (alpha, alpha, alpha, alpha for an image; the fill colour for texture 0, a white texel).
 */
static JSValue n_surfQuad(JSContext *ctx, JSValueConst self, int argc, JSValueConst *argv) {
  int target = ARGI(0), tex = ARGI(1), linear = JS_ToBool(ctx, argv[2]) ? 1 : 0, blend = ARGI(3) ? 1 : 0;
  if (!tex_by_id(target) || (tex && !tex_by_id(tex))) return JS_ThrowTypeError(ctx, "surfQuad: unknown texture");
  if (tex == target) return JS_ThrowTypeError(ctx, "surfQuad: a surface cannot draw itself");
  float x0 = (float)ARGF(4), y0 = (float)ARGF(5), x1 = (float)ARGF(6), y1 = (float)ARGF(7);
  float u0 = (float)ARGF(8), v0 = (float)ARGF(9), u1 = (float)ARGF(10), v1 = (float)ARGF(11);
  float r = (float)ARGF(12), g = (float)ARGF(13), b = (float)ARGF(14), a = (float)ARGF(15);
  if (sv_n + 6 > sv_cap) {
    sv_cap = sv_cap ? sv_cap * 2 : 1024;
    sv = SDL_realloc(sv, sizeof *sv * sv_cap);
  }
  SurfVert q[4] = {{x0, y0, u0, v0, r, g, b, a}, {x1, y0, u1, v0, r, g, b, a},
                   {x0, y1, u0, v1, r, g, b, a}, {x1, y1, u1, v1, r, g, b, a}};
  static const int tri[6] = {0, 1, 2, 2, 1, 3};
  for (int i = 0; i < 6; i++) sv[sv_n + (Uint32)i] = q[tri[i]];
  SurfDraw *last = sd_n ? &sd[sd_n - 1] : NULL;
  if (last && last->target == target && last->tex == tex && last->linear == linear && last->blend == blend) {
    last->count += 6;
  } else {
    if (sd_n == sd_cap) {
      sd_cap = sd_cap ? sd_cap * 2 : 64;
      sd = SDL_realloc(sd, sizeof *sd * (size_t)sd_cap);
    }
    sd[sd_n++] = (SurfDraw){target, tex, linear, blend, sv_n, 6};
  }
  sv_n += 6;
  return JS_UNDEFINED;
}

static JSValue n_surfClear(JSContext *ctx, JSValueConst self, int argc, JSValueConst *argv) {
  SDL_GPUTexture *t = tex_by_id(ARGI(0));
  if (!t) return JS_ThrowTypeError(ctx, "surfClear: unknown texture");
  clear_target(t);
  return JS_UNDEFINED;
}

/* putImageData of the whole surface: straight RGBA in, premultiplied as a canvas stores it. */
static JSValue n_surfPut(JSContext *ctx, JSValueConst self, int argc, JSValueConst *argv) {
  int id = ARGI(0);
  SDL_GPUTexture *t = tex_by_id(id);
  size_t n = 0;
  uint8_t *p = JS_GetArrayBuffer(ctx, &n, argv[1]);
  if (!t || !p || n != (size_t)tex_w[id] * (size_t)tex_h[id] * 4) return JS_ThrowTypeError(ctx, "surfPut: bad args");
  flush_surf();
  end_composite();
  if (!cmd) cmd = SDL_AcquireGPUCommandBuffer(dev);
  uint8_t *px = SDL_malloc(n);
  memcpy(px, p, n);
  premultiply(px, n);
  copy_rect(cmd, t, px, 0, 0, tex_w[id], tex_h[id], 4);
  SDL_free(px);
  return JS_UNDEFINED;
}

/*
 * Decode a WebP or a PNG to a premultiplied texture — how a canvas holds an ImageBitmap it
 * draws. (decodeWebp keeps the straight alpha the room's AiTarget passes expect.)
 */
static JSValue n_decodeImage(JSContext *ctx, JSValueConst self, int argc, JSValueConst *argv) {
  size_t n = 0;
  uint8_t *p = JS_GetArrayBuffer(ctx, &n, argv[0]);
  if (!p) return JS_EXCEPTION;
  int w = 0, h = 0;
  uint8_t *rgba = NULL;
  if (n >= 8 && !memcmp(p, "\x89PNG", 4)) {
    SDL_Surface *png = SDL_LoadPNG_IO(SDL_IOFromConstMem(p, n), true);
    SDL_Surface *conv = png ? SDL_ConvertSurface(png, SDL_PIXELFORMAT_RGBA32) : NULL;
    if (png) SDL_DestroySurface(png);
    if (!conv) return JS_ThrowTypeError(ctx, "PNG decode failed: %s", SDL_GetError());
    w = conv->w;
    h = conv->h;
    rgba = SDL_malloc((size_t)w * (size_t)h * 4);
    for (int y = 0; y < h; y++) memcpy(rgba + (size_t)y * (size_t)w * 4, (uint8_t *)conv->pixels + (size_t)y * (size_t)conv->pitch, (size_t)w * 4);
    SDL_DestroySurface(conv);
  } else {
    uint8_t *webp = WebPDecodeRGBA(p, n, &w, &h);
    if (!webp) return JS_ThrowTypeError(ctx, "WebP decode failed");
    rgba = SDL_malloc((size_t)w * (size_t)h * 4);
    memcpy(rgba, webp, (size_t)w * (size_t)h * 4);
    WebPFree(webp);
  }
  premultiply(rgba, (size_t)w * (size_t)h * 4);
  SDL_GPUTexture *t = make_texture(SDL_GPU_TEXTUREFORMAT_R8G8B8A8_UNORM, w, h, SDL_GPU_TEXTUREUSAGE_SAMPLER);
  upload(t, rgba, w, h, 4);
  SDL_free(rgba);
  JSValue o = JS_NewObject(ctx);
  JS_SetPropertyStr(ctx, o, "id", JS_NewInt32(ctx, add_texture(t, w, h)));
  JS_SetPropertyStr(ctx, o, "width", JS_NewInt32(ctx, w));
  JS_SetPropertyStr(ctx, o, "height", JS_NewInt32(ctx, h));
  return o;
}

static SDL_GPUGraphicsPipeline *surf_pipeline(bool dest_in) {
  SDL_GPUShaderCreateInfo vi = {0}, fi = {0};
  vi.code = fi.code = (const Uint8 *)SHADERS_MSL;
  vi.code_size = fi.code_size = sizeof(SHADERS_MSL) - 1;
  vi.format = fi.format = SDL_GPU_SHADERFORMAT_MSL;
  vi.entrypoint = "vs_surf";
  vi.stage = SDL_GPU_SHADERSTAGE_VERTEX;
  vi.num_uniform_buffers = 1;
  fi.entrypoint = "fs_surf";
  fi.stage = SDL_GPU_SHADERSTAGE_FRAGMENT;
  fi.num_samplers = 1;
  SDL_GPUShader *v = SDL_CreateGPUShader(dev, &vi), *f = SDL_CreateGPUShader(dev, &fi);
  if (!v || !f) die("surface shaders");
  SDL_GPUColorTargetDescription ct = {0};
  ct.format = SDL_GPU_TEXTUREFORMAT_R8G8B8A8_UNORM;
  ct.blend_state.enable_blend = true;
  /* source-over on premultiplied colour: (ONE, ONE_MINUS_SRC_ALPHA). destination-in keeps
     the destination where the source is opaque: (ZERO, SRC_ALPHA). Colour and alpha alike. */
  SDL_GPUBlendFactor sf = dest_in ? SDL_GPU_BLENDFACTOR_ZERO : SDL_GPU_BLENDFACTOR_ONE;
  SDL_GPUBlendFactor df = dest_in ? SDL_GPU_BLENDFACTOR_SRC_ALPHA : SDL_GPU_BLENDFACTOR_ONE_MINUS_SRC_ALPHA;
  ct.blend_state.src_color_blendfactor = ct.blend_state.src_alpha_blendfactor = sf;
  ct.blend_state.dst_color_blendfactor = ct.blend_state.dst_alpha_blendfactor = df;
  ct.blend_state.color_blend_op = ct.blend_state.alpha_blend_op = SDL_GPU_BLENDOP_ADD;
  SDL_GPUVertexBufferDescription vb = {.slot = 0, .pitch = sizeof(SurfVert), .input_rate = SDL_GPU_VERTEXINPUTRATE_VERTEX};
  SDL_GPUVertexAttribute attrs[3] = {
      {.location = 0, .buffer_slot = 0, .format = SDL_GPU_VERTEXELEMENTFORMAT_FLOAT2, .offset = 0},
      {.location = 1, .buffer_slot = 0, .format = SDL_GPU_VERTEXELEMENTFORMAT_FLOAT2, .offset = 8},
      {.location = 2, .buffer_slot = 0, .format = SDL_GPU_VERTEXELEMENTFORMAT_FLOAT4, .offset = 16},
  };
  SDL_GPUGraphicsPipelineCreateInfo pi = {0};
  pi.vertex_shader = v;
  pi.fragment_shader = f;
  pi.vertex_input_state.vertex_buffer_descriptions = &vb;
  pi.vertex_input_state.num_vertex_buffers = 1;
  pi.vertex_input_state.vertex_attributes = attrs;
  pi.vertex_input_state.num_vertex_attributes = 3;
  pi.primitive_type = SDL_GPU_PRIMITIVETYPE_TRIANGLELIST;
  pi.rasterizer_state.cull_mode = SDL_GPU_CULLMODE_NONE;
  pi.target_info.color_target_descriptions = &ct;
  pi.target_info.num_color_targets = 1;
  SDL_GPUGraphicsPipeline *gp = SDL_CreateGPUGraphicsPipeline(dev, &pi);
  if (!gp) die("surface pipeline");
  SDL_ReleaseGPUShader(dev, v);
  SDL_ReleaseGPUShader(dev, f);
  return gp;
}

/* ── input ─────────────────────────────────────────────────────────────────────── */
/*
 * Key transitions for the JS router, as the DOM KeyboardEvent.code strings the browser
 * game's router already reads ("+KeyI" down, "-KeyI" up). The gamepad is mapped onto the
 * same codes, so the game has one router and the controller is "a keyboard":
 *
 *   d-pad / left stick  little fish  KeyI KeyK KeyJ KeyL
 *   right stick         big fish     KeyW KeyS KeyA KeyD
 *   A (south)           switch fish  Space
 *   Y (north)           undo         Minus
 *   X (west)            restart      Backspace
 *   LB / RB             save / load  F2 / F3
 *   B (east)            back         Escape
 *
 * On the world map the same codes steer the selection (IJKL, WASD), open (Space) and back
 * out (Escape) — native/js/mapScreen.ts.
 */
#define EVQ 128
static char evq[EVQ][24];
static int evq_n;

static void push_event(bool down, const char *code) {
  if (evq_n >= EVQ) return;
  if (code[0] == '!') SDL_strlcpy(evq[evq_n++], code, sizeof evq[0]); /* not a key: "!blur" */
  else SDL_snprintf(evq[evq_n++], sizeof evq[0], "%c%s", down ? '+' : '-', code);
}

/*
 * The codes a keyboard can send that the router reads, or NULL. By physical key, as the
 * browser's `e.code` is — except undo. The browser matches undo on `e.key === '-'`, the
 * CHARACTER, because on a Czech QWERTZ keyboard `-` is not on the US Minus key
 * (src/app/main.ts, the Minus binding; src/app/undo.ts). So it is taken from the
 * layout-aware keycode here, and the physical Minus key sends nothing.
 */
static const char *code_of(SDL_Scancode sc, SDL_Keycode key) {
  static char buf[16];
  if (key == SDLK_MINUS) return "Minus";
  if (key == SDLK_KP_MINUS) return "NumpadSubtract";
  if (sc >= SDL_SCANCODE_A && sc <= SDL_SCANCODE_Z) { SDL_snprintf(buf, sizeof buf, "Key%c", 'A' + (sc - SDL_SCANCODE_A)); return buf; }
  if (sc >= SDL_SCANCODE_1 && sc <= SDL_SCANCODE_9) { SDL_snprintf(buf, sizeof buf, "Digit%c", '1' + (sc - SDL_SCANCODE_1)); return buf; }
  if (sc >= SDL_SCANCODE_F1 && sc <= SDL_SCANCODE_F12) { SDL_snprintf(buf, sizeof buf, "F%d", 1 + (sc - SDL_SCANCODE_F1)); return buf; }
  switch (sc) {
    case SDL_SCANCODE_0: return "Digit0";
    case SDL_SCANCODE_UP: return "ArrowUp";
    case SDL_SCANCODE_DOWN: return "ArrowDown";
    case SDL_SCANCODE_LEFT: return "ArrowLeft";
    case SDL_SCANCODE_RIGHT: return "ArrowRight";
    case SDL_SCANCODE_SPACE: return "Space";
    case SDL_SCANCODE_TAB: return "Tab";
    case SDL_SCANCODE_BACKSPACE: return "Backspace";
    case SDL_SCANCODE_ESCAPE: return "Escape";
    case SDL_SCANCODE_RETURN: return "Enter"; /* Ⓐ on the map, beside Space */
    case SDL_SCANCODE_KP_ENTER: return "NumpadEnter";
    default: return NULL;
  }
}

/* The gamepad's codes are reference-counted, so the d-pad and the left stick — both the
   little fish — cannot release a direction the other is still holding. */
#define NPADKEYS 16
static struct { const char *code; int held; } padkeys[NPADKEYS];

static void pad_key(const char *code, bool down) {
  int i = 0;
  while (i < NPADKEYS && padkeys[i].code && strcmp(padkeys[i].code, code)) i++;
  if (i == NPADKEYS) return;
  padkeys[i].code = code;
  if (down && padkeys[i].held++ == 0) push_event(true, code);
  if (!down && padkeys[i].held > 0 && --padkeys[i].held == 0) push_event(false, code);
}

static const char *button_code(Uint8 b) {
  switch (b) {
    case SDL_GAMEPAD_BUTTON_DPAD_UP: return "KeyI";
    case SDL_GAMEPAD_BUTTON_DPAD_DOWN: return "KeyK";
    case SDL_GAMEPAD_BUTTON_DPAD_LEFT: return "KeyJ";
    case SDL_GAMEPAD_BUTTON_DPAD_RIGHT: return "KeyL";
    case SDL_GAMEPAD_BUTTON_SOUTH: return "Space";
    case SDL_GAMEPAD_BUTTON_NORTH: return "Minus";
    case SDL_GAMEPAD_BUTTON_WEST: return "Backspace";
    case SDL_GAMEPAD_BUTTON_LEFT_SHOULDER: return "F2";
    case SDL_GAMEPAD_BUTTON_RIGHT_SHOULDER: return "F3";
    case SDL_GAMEPAD_BUTTON_EAST: return "Escape";
    default: return NULL;
  }
}

/*
 * A stick as four keys: the dominant axis past the dead zone is the one direction held,
 * and a held direction lets go only below a lower threshold, so a thumb resting near the
 * edge does not chatter between press and release. Engage at 0.5 of full deflection,
 * release below 0.35 (the controller spec's thresholds, from #165's gamepad.ts).
 */
typedef struct { SDL_GamepadAxis x, y; const char *code[4]; int held; } Stick; /* held: 0 none, 1..4 = up/down/left/right */
static Stick sticks[2] = {
    {SDL_GAMEPAD_AXIS_LEFTX, SDL_GAMEPAD_AXIS_LEFTY, {"KeyI", "KeyK", "KeyJ", "KeyL"}, 0},
    {SDL_GAMEPAD_AXIS_RIGHTX, SDL_GAMEPAD_AXIS_RIGHTY, {"KeyW", "KeyS", "KeyA", "KeyD"}, 0},
};

static void poll_sticks(void) {
  const int press = 16384, release = 11469; /* 0.5 and 0.35 of 32767 */
  for (int i = 0; i < 2; i++) {
    Stick *st = &sticks[i];
    int ax = pad ? SDL_GetGamepadAxis(pad, st->x) : 0, ay = pad ? SDL_GetGamepadAxis(pad, st->y) : 0;
    int dir = 0;
    if (SDL_abs(ax) >= SDL_abs(ay)) {
      if (ax <= -press) dir = 3; else if (ax >= press) dir = 4;
    } else {
      if (ay <= -press) dir = 1; else if (ay >= press) dir = 2;
    }
    if (!dir && st->held) {
      int v = st->held <= 2 ? ay : ax;
      if (SDL_abs(v) > release && ((st->held == 1 || st->held == 3) ? v < 0 : v > 0)) dir = st->held;
    }
    if (dir == st->held) continue;
    if (st->held) pad_key(st->code[st->held - 1], false);
    if (dir) pad_key(st->code[dir - 1], true);
    st->held = dir;
  }
}

static JSValue n_events(JSContext *ctx, JSValueConst self, int argc, JSValueConst *argv) {
  JSValue a = JS_NewArray(ctx);
  for (int i = 0; i < evq_n; i++) JS_SetPropertyUint32(ctx, a, (uint32_t)i, JS_NewString(ctx, evq[i]));
  evq_n = 0;
  return a;
}

/* ── persistence: the localStorage shim's file ─────────────────────────────────── */
/* --store, or store.json in the user's app-support dir (created on first use). */
static const char *store_file(void) {
  if (!store_path[0]) {
    char *dir = SDL_GetPrefPath("ff4e", "Fish Fillets 4ever");
    if (!dir) return NULL;
    SDL_snprintf(store_path, sizeof store_path, "%sstore.json", dir);
    SDL_free(dir);
  }
  return store_path;
}

static JSValue n_storePath(JSContext *ctx, JSValueConst self, int argc, JSValueConst *argv) {
  const char *path = store_file();
  return path ? JS_NewString(ctx, path) : JS_NULL;
}

/* The store, or (argv[0] true) the copy of it before the last write; null when absent. */
static JSValue n_storeLoad(JSContext *ctx, JSValueConst self, int argc, JSValueConst *argv) {
  const char *path = store_file();
  if (!path) return JS_NULL;
  char bak[2100];
  SDL_snprintf(bak, sizeof bak, "%s.bak", path);
  size_t size = 0;
  char *data = SDL_LoadFile(argc > 0 && JS_ToBool(ctx, argv[0]) ? bak : path, &size);
  if (!data) return JS_NULL;
  JSValue s = JS_NewStringLen(ctx, data, size);
  SDL_free(data);
  return s;
}

/* fsync, where the platform has it: a rename is only as durable as the bytes it names. */
#ifdef _WIN32
#define ff_fsync(f) _commit(_fileno(f))
#else
#define ff_fsync(f) fsync(fileno(f))
#endif

/*
 * Replace the store without ever leaving it half-written: the new bytes go to a sibling
 * and are flushed to disk, the current store becomes `.bak` (unless argv[1] says it is
 * damaged), and the sibling is renamed into place. A crash at any point leaves either the store or its backup whole, and the
 * reader (shims.ts) falls back to the backup.
 */
static JSValue n_storeSave(JSContext *ctx, JSValueConst self, int argc, JSValueConst *argv) {
  const char *path = store_file();
  if (!path) return JS_ThrowTypeError(ctx, "no place to keep the store: %s", SDL_GetError());
  size_t len = 0;
  const char *json = JS_ToCStringLen(ctx, &len, argv[0]);
  if (!json) return JS_EXCEPTION;
  char tmp[2100], bak[2100];
  SDL_snprintf(tmp, sizeof tmp, "%s.tmp", path);
  SDL_snprintf(bak, sizeof bak, "%s.bak", path);
  FILE *f = fopen(tmp, "wb");
  bool ok = f && fwrite(json, 1, len, f) == len && fflush(f) == 0 && ff_fsync(f) == 0;
  if (f) ok = (fclose(f) == 0) && ok;
  JS_FreeCString(ctx, json);
  /* argv[1]: the current store is the damaged one the reader fell back from — it must not
     become the backup, so it is simply replaced. */
  bool rotate = !(argc > 1 && JS_ToBool(ctx, argv[1]));
  if (ok && rotate && SDL_GetPathInfo(path, NULL)) ok = SDL_RenamePath(path, bak);
  if (ok) ok = SDL_RenamePath(tmp, path);
#ifndef _WIN32
  if (ok) { /* and the renames themselves */
    char dir[2048];
    SDL_strlcpy(dir, path, sizeof dir);
    char *slash = SDL_strrchr(dir, '/');
    if (slash) { *slash = 0; int fd = open(dir[0] ? dir : "/", O_RDONLY); if (fd >= 0) { fsync(fd); close(fd); } }
  }
#endif
  if (!ok) fprintf(stderr, "store: could not write %s: %s\n", path, SDL_GetError());
  return ok ? JS_UNDEFINED : JS_ThrowTypeError(ctx, "could not write %s: %s", path, SDL_GetError());
}

static JSValue n_args(JSContext *ctx, JSValueConst self, int argc, JSValueConst *argv) {
  JSValue a = JS_NewArray(ctx);
  for (int i = 0; i < js_argc; i++) JS_SetPropertyUint32(ctx, a, (uint32_t)i, JS_NewString(ctx, js_argv[i]));
  return a;
}

static JSValue n_quit(JSContext *ctx, JSValueConst self, int argc, JSValueConst *argv) {
  if (argc > 0) exit_code = ARGI(0);
  quit_requested = true;
  return JS_UNDEFINED;
}

static void poll_events(void) {
  SDL_Event e;
  while (SDL_PollEvent(&e)) {
    switch (e.type) {
      case SDL_EVENT_QUIT: quit_requested = true; break;
      /* Unfocused, a held key's keyup never arrives: the game drops it (main.ts's blur). */
      case SDL_EVENT_WINDOW_FOCUS_LOST: push_event(false, "!blur"); break;
      case SDL_EVENT_GAMEPAD_ADDED:
        if (!pad) {
          pad = SDL_OpenGamepad(e.gdevice.which);
          if (pad) SDL_Log("gamepad: %s", SDL_GetGamepadName(pad));
        }
        break;
      case SDL_EVENT_GAMEPAD_REMOVED:
        if (pad && SDL_GetGamepadID(pad) == e.gdevice.which) {
          SDL_CloseGamepad(pad);
          pad = NULL;
          /* An unplugged pad sends no button-up: let go of whatever it held. */
          for (int i = 0; i < NPADKEYS && padkeys[i].code; i++)
            if (padkeys[i].held) { padkeys[i].held = 0; push_event(false, padkeys[i].code); }
          sticks[0].held = sticks[1].held = 0;
        }
        break;
      case SDL_EVENT_GAMEPAD_BUTTON_DOWN:
      case SDL_EVENT_GAMEPAD_BUTTON_UP: {
        const char *code = button_code(e.gbutton.button);
        if (code) pad_key(code, e.type == SDL_EVENT_GAMEPAD_BUTTON_DOWN);
        break;
      }
      case SDL_EVENT_KEY_DOWN:
      case SDL_EVENT_KEY_UP: {
        if (e.key.repeat) break; /* the game repeats a held key itself (KeyRoom) */
        const char *code = code_of(e.key.scancode, e.key.key);
        if (code) push_event(e.type == SDL_EVENT_KEY_DOWN, code);
        break;
      }
      default: break;
    }
  }
  poll_sticks();
}

/* ── JS runtime plumbing ───────────────────────────────────────────────────────── */
static void report(JSContext *ctx) {
  JSValue ex = JS_GetException(ctx);
  const char *s = JS_ToCString(ctx, ex);
  JSValue st = JS_GetPropertyStr(ctx, ex, "stack");
  const char *stack = JS_IsUndefined(st) ? NULL : JS_ToCString(ctx, st);
  fprintf(stderr, "JS exception: %s\n%s\n", s ? s : "?", stack ? stack : "");
  if (stack) JS_FreeCString(ctx, stack);
  if (s) JS_FreeCString(ctx, s);
  JS_FreeValue(ctx, st);
  JS_FreeValue(ctx, ex);
}

static void drain_jobs(JSRuntime *rt) {
  JSContext *c;
  int r;
  while ((r = JS_ExecutePendingJob(rt, &c)) != 0) {
    if (r < 0) report(c);
  }
}

/* Call globalThis[name]() if it is a function. */
static bool call_global(JSContext *ctx, const char *name) {
  JSValue g = JS_GetGlobalObject(ctx);
  JSValue f = JS_GetPropertyStr(ctx, g, name);
  bool called = false;
  if (JS_IsFunction(ctx, f)) {
    JSValue r = JS_Call(ctx, f, g, 0, NULL);
    if (JS_IsException(r)) { report(ctx); quit_requested = true; exit_code = 1; }
    JS_FreeValue(ctx, r);
    called = true;
  }
  JS_FreeValue(ctx, f);
  JS_FreeValue(ctx, g);
  return called;
}

static void install(JSContext *ctx) {
  static const struct { const char *name; JSCFunction *fn; int len; } fns[] = {
      {"print", n_print, 1},           {"now", n_now, 0},
      {"readFile", n_readFile, 1},     {"utf8", n_utf8, 1},
      {"decodeWebp", n_decodeWebp, 1}, {"releaseTexture", n_releaseTexture, 1},
      {"decodeWebpRgba", n_decodeWebpRgba, 1}, {"createTexture", n_createTexture, 4},
      {"updateTexture", n_updateTexture, 6}, {"mirror", n_mirror, 12},
      {"setRandTable", n_setRandTable, 1},
      {"begin", n_begin, 2},           {"fill", n_fill, 3},
      {"fillRect", n_fillRect, 7},     {"blit", n_blit, 6},
      {"background", n_background, 12}, {"setBands", n_setBands, 2},
      {"disintegrate", n_disintegrate, 8},
      {"present", n_present, 0},       {"saveComposite", n_saveComposite, 1},
      {"decodeImage", n_decodeImage, 1}, {"surfCreate", n_surfCreate, 2},
      {"surfQuad", n_surfQuad, 16},     {"surfClear", n_surfClear, 1},
      {"surfPut", n_surfPut, 2},        {"presentTexture", n_presentTexture, 1},
      {"saveTexture", n_saveTexture, 2},
      {"events", n_events, 0},
      {"storeLoad", n_storeLoad, 1},   {"storeSave", n_storeSave, 2},
      {"storePath", n_storePath, 0},
      {"args", n_args, 0},             {"quit", n_quit, 0},
  };
  JSValue g = JS_GetGlobalObject(ctx);
  JSValue n = JS_NewObject(ctx);
  for (size_t i = 0; i < sizeof fns / sizeof fns[0]; i++)
    JS_SetPropertyStr(ctx, n, fns[i].name, JS_NewCFunction(ctx, fns[i].fn, fns[i].name, fns[i].len));
  JS_SetPropertyStr(ctx, g, "__native", n);
  JS_FreeValue(ctx, g);
}

int main(int argc, char **argv) {
  if (argc < 2) {
    fprintf(stderr, "usage: %s <bundle.js> --root <public dir> [--room N] [--store F] [--headless ...]\n", argv[0]);
    return 2;
  }
  js_argc = argc - 2;
  js_argv = argv + 2;
  SDL_strlcpy(root, "public", sizeof root);
  for (int i = 2; i < argc; i++) {
    if (!strcmp(argv[i], "--root") && i + 1 < argc) SDL_strlcpy(root, argv[i + 1], sizeof root);
    if (!strcmp(argv[i], "--store") && i + 1 < argc) SDL_strlcpy(store_path, argv[i + 1], sizeof store_path);
    if (!strcmp(argv[i], "--headless")) headless = true;
  }

  /* The GPU device needs the video subsystem even when no window is ever opened. */
  if (!SDL_Init(headless ? SDL_INIT_VIDEO : (SDL_INIT_VIDEO | SDL_INIT_GAMEPAD))) die("SDL_Init");
  dev = SDL_CreateGPUDevice(SDL_GPU_SHADERFORMAT_MSL, false, NULL);
  if (!dev) die("SDL_CreateGPUDevice");
  SDL_Log("GPU driver: %s", SDL_GetGPUDeviceDriver(dev));
  SDL_GPUTextureFormat swap_fmt = SDL_GPU_TEXTUREFORMAT_B8G8R8A8_UNORM;
  if (!headless) {
    win = SDL_CreateWindow("Fish Fillets 4ever", 1280, 800, SDL_WINDOW_RESIZABLE | SDL_WINDOW_HIGH_PIXEL_DENSITY);
    if (!win || !SDL_ClaimWindowForGPUDevice(dev, win)) die("window");
    swap_fmt = SDL_GetGPUSwapchainTextureFormat(dev, win);
  }

  const SDL_GPUTextureFormat rgba = SDL_GPU_TEXTUREFORMAT_R8G8B8A8_UNORM;
  p_fill = pipeline("vs_rect", 1, "fs_fill", 0, rgba, false, true);
  p_bg = pipeline("vs_full", 0, "fs_bg", 3, rgba, false, false);
  p_sprite = pipeline("vs_rect", 1, "fs_sprite", 1, rgba, true, true);
  p_disint = pipeline("vs_rect", 1, "fs_disint", 2, rgba, true, true);
  p_mirror = pipeline("vs_full", 0, "fs_mirror", 2, rgba, false, false);
  p_present = pipeline("vs_full", 0, "fs_present", 1, swap_fmt, false, false);
  SDL_GPUSamplerCreateInfo si = {0};
  si.min_filter = si.mag_filter = SDL_GPU_FILTER_NEAREST;
  si.mipmap_mode = SDL_GPU_SAMPLERMIPMAPMODE_NEAREST;
  si.address_mode_u = si.address_mode_v = si.address_mode_w = SDL_GPU_SAMPLERADDRESSMODE_CLAMP_TO_EDGE;
  s_nearest = SDL_CreateGPUSampler(dev, &si);
  si.min_filter = si.mag_filter = SDL_GPU_FILTER_LINEAR;
  s_linear = SDL_CreateGPUSampler(dev, &si);
  /* A real 1x1 texel, not nothing: the band texture is bound on every background pass
     (GlAiScreen gives its uBands the same 1x1 black for the same reason). */
  band_tex = make_texture(SDL_GPU_TEXTUREFORMAT_R8G8B8A8_UNORM, 1, 1, SDL_GPU_TEXTUREUSAGE_SAMPLER);
  band_w = 1;
  upload(band_tex, (const uint8_t[4]){0, 0, 0, 255}, 1, 1, 4);
  p_surf[0] = surf_pipeline(false);
  p_surf[1] = surf_pipeline(true);
  white_tex = make_texture(SDL_GPU_TEXTUREFORMAT_R8G8B8A8_UNORM, 1, 1, SDL_GPU_TEXTUREUSAGE_SAMPLER);
  upload(white_tex, (const uint8_t[4]){255, 255, 255, 255}, 1, 1, 4);

  JSRuntime *rt = JS_NewRuntime();
  JS_SetMaxStackSize(rt, 8 * 1024 * 1024);
  JSContext *ctx = JS_NewContext(rt);
  install(ctx);
  size_t len = 0;
  char *src = SDL_LoadFile(argv[1], &len);
  if (!src) die(argv[1]);
  Uint64 t0 = SDL_GetTicksNS();
  JSValue r = JS_Eval(ctx, src, len, argv[1], JS_EVAL_TYPE_GLOBAL);
  SDL_free(src);
  if (JS_IsException(r)) { report(ctx); return 1; }
  JS_FreeValue(ctx, r);
  SDL_Log("bundle evaluated in %.1f ms", (double)(SDL_GetTicksNS() - t0) / 1e6);

  while (!quit_requested) {
    if (!headless) poll_events();
    drain_jobs(rt);
    call_global(ctx, "__timers");
    drain_jobs(rt);
    if (!call_global(ctx, "__frame")) SDL_Delay(1);
    drain_jobs(rt);
  }

  JS_FreeContext(ctx);
  JS_FreeRuntime(rt);
  SDL_DestroyGPUDevice(dev);
  SDL_Quit();
  return exit_code;
}
