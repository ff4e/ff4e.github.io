/*
 * GlAiScreen.mirrorGlass: the reflection reads the composite as it was before the pass,
 * so GL renders into the other half of a ping-pong pair. Here the composite is copied
 * aside instead and the pass draws back over it — the same pixels, one texture fewer
 * to keep current.
 */
static JSValue n_mirror(JSContext *ctx, JSValueConst self, int argc, JSValueConst *argv) {
  SDL_GPUTexture *mask = tex_by_id(ARGI(0));
  if (!mask || !comp) return JS_ThrowTypeError(ctx, "mirror: unknown mask");
  MirrorU u = {ARGI(1), ARGI(2), ARGI(3), ARGI(4), ARGI(5), ARGI(6), ARGI(7), ARGI(8), ARGI(9), ARGI(10), ARGI(11), 0};
  end_composite();
  if (!comp_snap) comp_snap = make_texture(SDL_GPU_TEXTUREFORMAT_R8G8B8A8_UNORM, comp_w, comp_h, SDL_GPU_TEXTUREUSAGE_SAMPLER);
  SDL_GPUCopyPass *cp = SDL_BeginGPUCopyPass(cmd);
  SDL_GPUTextureLocation from = {.texture = comp}, to = {.texture = comp_snap};
  SDL_CopyGPUTextureToTexture(cp, &from, &to, (Uint32)comp_w, (Uint32)comp_h, 1, false);
  SDL_EndGPUCopyPass(cp);
  open_composite(SDL_GPU_LOADOP_LOAD);
  use(p_mirror);
  SDL_PushGPUFragmentUniformData(cmd, 0, &u, sizeof u);
  SDL_GPUTextureSamplerBinding b[2] = {{comp_snap, s_nearest}, {mask, s_nearest}};
  SDL_BindGPUFragmentSamplers(pass, 0, b, 2);
  SDL_DrawGPUPrimitives(pass, 3, 1, 0, 0);
  return JS_UNDEFINED;
}

typedef struct { float size[2], origin[2], footprint[2]; int32_t taps, pad; } PresentU;
typedef struct { float origin[2]; int32_t size[2]; } OverlayU;

/* Where content of w×h lands in a sw×sh window: as large as fits, centred, whole pixels. */
static void letterbox(int w, int h, Uint32 sw, Uint32 sh, float *ox, float *oy, float *dw, float *dh) {
  float scale = SDL_min((float)sw / (float)w, (float)sh / (float)h);
  *dw = SDL_floorf((float)w * scale);
  *dh = SDL_floorf((float)h * scale);
  *ox = SDL_floorf(((float)sw - *dw) / 2);
  *oy = SDL_floorf(((float)sh - *dh) / 2);
}

/*
 * Box-filter `src` (w×h) into the window, letterboxed, then draw `overlay` (if any) over
 * the same rect at one texel per window pixel, premultiplied — the subtitles, laid out
 * for exactly that rect (`presentRect`) — and submit the frame.
 */
static void present_tex(SDL_GPUTexture *src, int w, int h, int overlay, bool overlay_window, int ui) {
  flush_surf();
  end_composite();
  /* Nothing recorded this frame (a surface painted once and shown again, a movie frame
     uploaded on its own command buffer) still has to reach the window, and pace the loop. */
  if (!cmd && src && win) cmd = SDL_AcquireGPUCommandBuffer(dev);
  if (!cmd) return;
  SDL_GPUTexture *swap = NULL;
  Uint32 sw = 0, sh = 0;
  if (src && win && SDL_WaitAndAcquireGPUSwapchainTexture(cmd, win, &swap, &sw, &sh) && swap) {
    float ox, oy, dw, dh;
    letterbox(w, h, sw, sh, &ox, &oy, &dw, &dh);
    SDL_GPUColorTargetInfo ct = {0};
    ct.texture = swap;
    ct.load_op = SDL_GPU_LOADOP_CLEAR;
    ct.store_op = SDL_GPU_STOREOP_STORE;
    SDL_GPURenderPass *rp = SDL_BeginGPURenderPass(cmd, &ct, 1, NULL);
    SDL_GPUViewport vp = {ox, oy, dw, dh, 0, 1};
    SDL_SetGPUViewport(rp, &vp);
    SDL_BindGPUGraphicsPipeline(rp, p_present);
    float rx = (float)w / dw, ry = (float)h / dh;
    int taps = (int)SDL_ceilf(SDL_max(rx, ry));
    taps = taps < 1 ? 1 : taps > 4 ? 4 : taps;
    PresentU u = {{dw, dh}, {ox, oy}, {rx / (float)w, ry / (float)h}, taps, 0};
    SDL_PushGPUFragmentUniformData(cmd, 0, &u, sizeof u);
    SDL_GPUTextureSamplerBinding b = {src, s_linear};
    SDL_BindGPUFragmentSamplers(rp, 0, &b, 1);
    SDL_DrawGPUPrimitives(rp, 3, 1, 0, 0);
    SDL_GPUTexture *ov = tex_by_id(overlay);
    if (ov) {
      if (overlay_window) { /* the overlay is the whole window's, not the content's rect */
        SDL_GPUViewport whole = {0, 0, (float)sw, (float)sh, 0, 1};
        SDL_SetGPUViewport(rp, &whole);
        ox = oy = 0;
      }
      SDL_BindGPUGraphicsPipeline(rp, p_overlay);
      OverlayU ou = {{ox, oy}, {tex_w[overlay], tex_h[overlay]}};
      SDL_PushGPUFragmentUniformData(cmd, 0, &ou, sizeof ou);
      SDL_GPUTextureSamplerBinding ob = {ov, s_nearest};
      SDL_BindGPUFragmentSamplers(rp, 0, &ob, 1);
      SDL_DrawGPUPrimitives(rp, 3, 1, 0, 0);
    }
    /* The UI layer (menus, the button legend): the whole window, one texel per pixel. */
    SDL_GPUTexture *uit = tex_by_id(ui);
    if (uit) {
      SDL_GPUViewport full = {0, 0, (float)sw, (float)sh, 0, 1};
      SDL_SetGPUViewport(rp, &full);
      SDL_BindGPUGraphicsPipeline(rp, p_overlay);
      OverlayU uu = {{0, 0}, {tex_w[ui], tex_h[ui]}};
      SDL_PushGPUFragmentUniformData(cmd, 0, &uu, sizeof uu);
      SDL_GPUTextureSamplerBinding ub = {uit, s_nearest};
      SDL_BindGPUFragmentSamplers(rp, 0, &ub, 1);
      SDL_DrawGPUPrimitives(rp, 3, 1, 0, 0);
    }
    SDL_EndGPURenderPass(rp);
  }
  SDL_SubmitGPUCommandBuffer(cmd);
  cmd = NULL;
}

