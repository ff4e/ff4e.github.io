// node --import tsx tools/build-native-menu-palette.mjs [--write]
// FF_UI_PORT points at this worktree's dev server; the default operation checks drift.
import assert from 'node:assert/strict';
import { readFileSync, writeFileSync } from 'node:fs';
import { chromium } from 'playwright';
import { ROOMS } from '../src/data/roomTable.ts';

const browser = await chromium.launch();
try {
  const page = await browser.newPage();
  const fixture = `http://127.0.0.1:${process.env.FF_UI_PORT ?? '5173'}/__native-menu-palette`;
  await page.route(fixture, route => route.fulfill({
    contentType: 'text/html', body: '<!doctype html><html></html>',
  }));
  await page.goto(fixture);
  const hues = [];
  for (const room of ROOMS) {
    hues.push(await page.evaluate(async name => {
      const { roomTone } = await import('/src/platform/nativeMenuPalette.ts');
      const image = new Image();
      image.src = `/enhanced-ai/${name}/w.webp`;
      await image.decode();
      const canvas = document.createElement('canvas');
      canvas.width = canvas.height = 64;
      const ctx = canvas.getContext('2d');
      ctx.drawImage(image, 0, 0, 64, 64);
      return roomTone(ctx.getImageData(0, 0, 64, 64).data).hue;
    }, room.jmeno));
  }
  const output = [
    '// Generated by tools/build-native-menu-palette.mjs from static AI wall artwork.',
    '// Room accents are deliberately independent of animated frames and runtime art tiers.',
    'export const NATIVE_MENU_HUES: readonly (number | null)[] = [',
    ...ROOMS.map((r, i) => `  ${hues[i]}, // ${r.num}: ${r.jmeno}`),
    '];', '',
  ].join('\n');
  const target = new URL('../src/data/nativeMenuHues.ts', import.meta.url);
  if (process.argv.includes('--write')) writeFileSync(target, output);
  else assert.equal(readFileSync(target, 'utf8'), output, 'Native room palette drifted; regenerate and review');
  console.log(`PASS: ${hues.length} static room accents ${process.argv.includes('--write') ? 'generated' : 'verified'}`);
} finally {
  await browser.close();
}
